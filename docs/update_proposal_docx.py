def main():
    src = Path(sys.argv[1])
    backup = src.with_name(src.stem + ' — גיבוי לפני עדכון' + src.suffix)
    if not backup.exists():
        shutil.copy2(src, backup)
        print(f'backup -> {backup.name}')

    doc = Document(str(src))
    blocks = list(iter_blocks(doc))

    # formatting templates lifted from the innovation paragraph
    tmpl_rtl = copy.deepcopy(blocks[39].runs[0]._r)
    tmpl_ltr = copy.deepcopy(blocks[39].runs[28]._r)

    for idx, text in UPDATES.items():
        set_text(blocks[idx], text, tmpl_rtl, tmpl_ltr)
        print(f'[{idx}] updated ({len(text)} chars)')

    # work plan: rewrite the 9 existing lines, append the rest as new paragraphs
    for i, line in enumerate(PLAN[:PLAN_LAST - PLAN_FIRST + 1]):
        set_text(blocks[PLAN_FIRST + i], line, tmpl_rtl, tmpl_ltr)
    anchor = blocks[PLAN_LAST]._p
    for line in PLAN[PLAN_LAST - PLAN_FIRST + 1:]:
        new_p = copy.deepcopy(blocks[PLAN_LAST]._p)
        anchor.addnext(new_p)
        anchor = new_p
        set_text(Paragraph(new_p, blocks[PLAN_LAST]._parent), line, tmpl_rtl, tmpl_ltr)
    print(f'work plan: {len(PLAN)} stages')

    doc.save(str(src))
    print(f'saved -> {src.name}')


