from docx import Document
from docx.oxml.ns import qn
from docx.table import Table
from docx.text.paragraph import Paragraph
from docx.text.run import Run

HEB = re.compile('[֐-׿יִ-ﭏ]')
LAT = re.compile(r'[A-Za-z]')


def iter_blocks(doc):
    for child in doc.element.body.iterchildren():
        if child.tag == qn('w:p'):
            yield Paragraph(child, doc)
        elif child.tag == qn('w:tbl'):
            yield Table(child, doc)


def segments(text):
    """Split text into (is_rtl, chunk) runs; neutral chars join the current chunk."""
    out, cur, buf = [], None, ''
    for ch in text:
        if HEB.match(ch):
            d = True
        elif LAT.match(ch):
            d = False
        else:
            buf += ch
            continue
        if cur is None or d == cur:
            cur = d
            buf += ch
        else:
            out.append((cur, buf))
            cur, buf = d, ch
    if buf:
        out.append((True if cur is None else cur, buf))
    return out


def set_text(para, text, tmpl_rtl, tmpl_ltr):
    for r in list(para._p.findall(qn('w:r'))):
        para._p.remove(r)
    for is_rtl, chunk in segments(text):
        el = copy.deepcopy(tmpl_rtl if is_rtl else tmpl_ltr)
        for child in list(el):
            if child.tag != qn('w:rPr'):
                el.remove(child)
        para._p.append(el)
        Run(el, para).text = chunk


